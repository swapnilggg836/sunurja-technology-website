/* =========================================
   MAKE ARTICLE DATA AVAILABLE TO DETAILS PAGE
========================================= */

window.blogs = blogs;


/* =========================================
   DOM ELEMENTS
========================================= */

document.addEventListener("DOMContentLoaded", function () {

    const blogGrid = document.getElementById("blogGrid");

    // Details page does not require listing functionality.
    if (!blogGrid) return;

    const blogSearch = document.getElementById("blogSearch");

    const filterButtons = document.querySelectorAll(".filter-btn");

    const blogCount = document.getElementById("blogCount");

    const noResults = document.getElementById("noResults");

    const clearSearch = document.getElementById("clearSearch");

    const resetFilters = document.getElementById("resetFilters");


    let currentCategory = "All";


    /* =========================================
       SAFE HTML OUTPUT
    ========================================= */

    function escapeHTML(value) {

        return String(value).replace(/[&<>"']/g, function (character) {

            const entities = {
                "&": "&amp;",
                "<": "&lt;",
                ">": "&gt;",
                '"': "&quot;",
                "'": "&#039;"
            };

            return entities[character];

        });

    }


    /* =========================================
       DISPLAY BLOG CARDS
    ========================================= */

    function displayBlogs(blogList) {

        blogGrid.innerHTML = "";

        blogCount.textContent =
            `Showing ${blogList.length} ${blogList.length === 1 ? "article" : "articles"}`;

        noResults.hidden = blogList.length !== 0;

        blogGrid.hidden = blogList.length === 0;

        blogList.forEach(function (blog) {

            const blogCard = document.createElement("article");

            blogCard.className = "blog-card";

            blogCard.innerHTML = `
    <div class="blog-card-image">
        <img src="${escapeHTML(blog.image)}" alt="${escapeHTML(blog.title)}" loading="lazy"
             onerror="this.onerror=null;this.src='../assets/images/blog/solar-electricity.jpg';">
        <span class="blog-card-category">${escapeHTML(blog.category)}</span>
    </div>
    <div class="blog-card-content">
        <div class="blog-card-meta">
            <span><i class="fa-regular fa-calendar"></i> ${escapeHTML(blog.date)}</span>
            <span><i class="fa-regular fa-clock"></i> ${escapeHTML(blog.readingTime)}</span>
        </div>
        <h3 class="blog-card-title">${escapeHTML(blog.title)}</h3>
        <p class="blog-card-description">${escapeHTML(blog.description)}</p>
        <div class="blog-card-footer">
            <span class="blog-card-author"><i class="fa-regular fa-user"></i> ${escapeHTML(blog.author)}</span>
            <a href="blog-details.html?id=${blog.id}" class="blog-card-readmore">Read More <span>→</span></a>
        </div>
    </div>`;

            blogGrid.appendChild(blogCard);

        });

    }


    /* =========================================
       FILTER BLOGS
    ========================================= */

    function filterBlogs() {

        const searchText = blogSearch.value
            .toLowerCase()
            .trim();

        const filteredBlogs = blogs.filter(function (blog) {

            const matchesCategory =
                currentCategory === "All" ||
                blog.category === currentCategory;

            const searchableText = [

                blog.title,
                blog.description,
                blog.category,
                blog.author,
                blog.subtitle

            ].join(" ").toLowerCase();

            const matchesSearch =
                searchableText.includes(searchText);

            return matchesCategory && matchesSearch;

        });

        displayBlogs(filteredBlogs);

    }


    /* =========================================
       CATEGORY FILTER EVENTS
    ========================================= */

    filterButtons.forEach(function (button) {

        button.addEventListener("click", function () {

            filterButtons.forEach(function (btn) {

                btn.classList.remove("active");

                btn.setAttribute("aria-pressed", "false");

            });

            button.classList.add("active");

            button.setAttribute("aria-pressed", "true");

            currentCategory = button.dataset.category;

            filterBlogs();

        });

    });


    /* =========================================
       SEARCH EVENT
    ========================================= */

    blogSearch.addEventListener("input", filterBlogs);


    /* =========================================
       CLEAR SEARCH
    ========================================= */

    clearSearch.addEventListener("click", function () {

        blogSearch.value = "";

        filterBlogs();

        blogSearch.focus();

    });


    /* =========================================
       RESET FILTERS
    ========================================= */

    resetFilters.addEventListener("click", function () {

        currentCategory = "All";

        blogSearch.value = "";

        filterButtons.forEach(function (button) {

            const isAll = button.dataset.category === "All";

            button.classList.toggle("active", isAll);

            button.setAttribute("aria-pressed", String(isAll));

        });

        filterBlogs();

    });


    /* =========================================
       INITIALIZE BLOG PAGE
    ========================================= */

    displayBlogs(blogs);
    window.blogs = blogs;

});
